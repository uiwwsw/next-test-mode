#!/usr/bin/env node
import {
  existsSync,
  lstatSync,
  mkdirSync,
  readFileSync,
  unlinkSync,
  writeFileSync,
} from "node:fs";
import { dirname, join, relative, resolve } from "node:path";

import { templates, legacyTemplates } from "./templates.mjs";

const args = process.argv.slice(2);
const usage = "Usage: next-test-mode init [--dir <app-directory>] [--migrate]";
if (!args.length || args.includes("--help") || args.includes("-h")) {
  console.log(
    `${usage}\nCreates Next.js App Router instrumentation and a Draft Mode route. Existing custom files are never overwritten.`,
  );
} else {
  try {
    if (args.shift() !== "init") throw new Error(usage);
    let directory = ".";
    let migrate = false;
    while (args.length) {
      const arg = args.shift();
      if (arg === "--dir" && args.length) directory = args.shift();
      else if (arg === "--migrate") migrate = true;
      else if (arg !== "--next") throw new Error(usage);
    }
    const root = resolve(directory);
    const manifest = JSON.parse(
      readFileSync(join(root, "package.json"), "utf8"),
    );
    if (!manifest.dependencies?.next && !manifest.devDependencies?.next)
      throw new Error(
        "Run this in a Next.js app, or pass --dir <app-directory>.",
      );
    const folder = existsSync(join(root, "app"))
      ? root
      : existsSync(join(root, "src/app"))
        ? join(root, "src")
        : null;
    if (!folder)
      throw new Error(
        "Automatic Draft Mode setup requires a Next.js App Router app (app/ or src/app/).",
      );
    const extension = existsSync(join(root, "tsconfig.json")) ? "ts" : "js";
    const snippets = templates(extension);
    const exists = (path) => {
      try {
        lstatSync(path);
        return true;
      } catch (error) {
        if (error.code === "ENOENT") return false;
        throw error;
      }
    };
    const planned = Object.entries(snippets).map(([name, snippet]) => ({
      name,
      snippet,
      file: join(folder, `${name}.${extension}`),
    }));
    const conflicts = [];
    for (const item of planned) {
      for (
        let parent = dirname(item.file);
        parent !== root;
        parent = dirname(parent)
      ) {
        if (
          exists(parent) &&
          (lstatSync(parent).isSymbolicLink() ||
            !lstatSync(parent).isDirectory())
        ) {
          conflicts.push(relative(root, parent));
          break;
        }
      }
      for (const location of [root, join(root, "src")])
        for (const ext of [
          "ts",
          "js",
          "tsx",
          "jsx",
          "mjs",
          "cjs",
          "mts",
          "cts",
        ]) {
          const file = join(location, `${item.name}.${ext}`);
          if (!exists(file)) continue;
          const stat = lstatSync(file);
          if (stat.isSymbolicLink() || !stat.isFile() || file !== item.file) {
            conflicts.push(relative(root, file));
            continue;
          }
          const content = readFileSync(file, "utf8");
          if (content === item.snippet) {
            item.skip = true;
            continue;
          }
          // App-owned catalogs and adapters are meant to be edited after init.
          if (
            item.name.startsWith("test-mode/") &&
            content.startsWith("// Generated by @uiwwsw/next-test-mode\n")
          ) {
            item.skip = true;
            continue;
          }
          if (
            migrate &&
            (legacyTemplates[item.name] ?? [])
              .flatMap((value) => [
                value,
                value.replaceAll("@uiwwsw/test-mode", "@uiwwsw/next-test-mode"),
              ])
              .includes(content.trim())
          )
            item.previous = content;
          else conflicts.push(relative(root, file));
        }
    }
    if (conflicts.length)
      throw new Error(
        `Existing custom setup: ${conflicts.join(", ")}.\nNo files changed. Merge these calls into your hooks, or use --migrate for unchanged 0.5/0.6-generated files:\n${planned.map((item) => `\n${relative(root, item.file)}:\n${item.snippet}`).join("")}`,
      );
    const written = [];
    try {
      for (const item of planned) {
        if (item.skip) continue;
        mkdirSync(dirname(item.file), { recursive: true });
        writeFileSync(item.file, item.snippet, {
          flag: item.previous === undefined ? "wx" : "w",
        });
        written.push(item);
      }
    } catch (error) {
      for (const item of written.reverse()) {
        if (item.previous === undefined) unlinkSync(item.file);
        else writeFileSync(item.file, item.previous);
      }
      throw error;
    }
    console.log(
      `${written.length ? "Configured" : "Already configured"} Next Test Mode: ${planned.map((item) => relative(root, item.file)).join(", ")}.\nEdit test-mode/catalog to keep test data separate from application code.\nRestart your dev server, then use your API pathname in Console:\n  test.patch('/api/cart', { total: 9.99 });\n  test.cache.status();\n  test.cache.bypass();\n  test.cache.restore();\nDraft Mode starts automatically; test.clear() returns to ordinary cached pages.\nFor a QA production build, set NEXT_PUBLIC_NEXT_TEST_MODE=1 at build and runtime.\nCSR, SSR, ISR and SSG previews use the same fetch calls. JSON state limit: 3500 encoded bytes.`,
    );
  } catch (error) {
    console.error(error.message);
    process.exitCode = 1;
  }
}
